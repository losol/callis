/**
 * Embeds the unchanged UCUM essence file in `src/essence/ucum-essence-xml.ts` as one string, so the
 * package can read it at startup without file system or network access.
 *
 * Usage: `pnpm --filter @callis/ucum embed` writes the module; `--check` only verifies that the
 * committed module matches `data/ucum-essence.xml`. Both first verify the pinned checksums in
 * `data/source.json`, so a changed data file is never embedded by accident.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface SourceFile {
  readonly packagePath: string;
  readonly bytes: number;
  readonly sha256: string;
}

interface Source {
  readonly repository: string;
  readonly commit: string;
  readonly files: Readonly<Record<string, SourceFile>>;
}

const packageDir = fileURLToPath(new URL('../', import.meta.url));
const outputPath = `${packageDir}src/essence/ucum-essence-xml.ts`;

/** Reads `data/source.json` and checks every listed file against its size and SHA-256. */
function verifySources(): { readonly source: Source; readonly essence: Buffer } {
  const source = JSON.parse(readFileSync(`${packageDir}data/source.json`, 'utf8')) as Source;
  let essence: Buffer | undefined;
  for (const [name, file] of Object.entries(source.files)) {
    const bytes = readFileSync(`${packageDir}${file.packagePath}`);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    if (bytes.length !== file.bytes || sha256 !== file.sha256) {
      throw new Error(`${file.packagePath} does not match ${name} at ${source.commit}`);
    }
    if (name === 'ucum-essence.xml') essence = bytes;
  }
  if (essence === undefined) throw new Error('data/source.json does not list ucum-essence.xml');
  return { source, essence };
}

/** The generated module for the given essence bytes. */
function renderModule(source: Source, essence: Buffer): string {
  // The file is 7-bit ASCII (its declaration says so), so a JavaScript string holds it exactly.
  if (!essence.every((byte) => byte < 0x80)) throw new Error('ucum-essence.xml is not ASCII');
  const text = essence.toString('latin1');
  const literal = text
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
  const sha256 = createHash('sha256').update(essence).digest('hex');
  return `// Generated by scripts/embed-essence.ts from data/ucum-essence.xml. Do not edit by hand.

/*!
 * The Unified Code for Units of Measure (UCUM), ucum-essence.xml, unchanged:
 * ${source.repository}/blob/${source.commit}/ucum-essence.xml
 * SHA-256 ${sha256}
 *
 * Copyright 1999-2024 Regenstrief Institute, Inc. All rights reserved.
 * Licensed under the UCUM License, Version 1.1 (the "License"); you may not use this file except
 * in compliance with the License. You may obtain a copy of the License at
 * https://unitsofmeasure.org/license, and in UCUM-LICENSE.md of this package.
 *
 * Unless required by applicable law or agreed to in writing, software distributed under the
 * License is distributed on an "AS IS" BASIS, WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either
 * express or implied. See the License for the specific language governing permissions and
 * limitations under the License.
 */

/** The text of the UCUM essence file, byte for byte as published (see \`data/source.json\`). */
export const UCUM_ESSENCE_XML: string =
  '${literal}';
`;
}

const isCheck = process.argv.includes('--check');
const { source, essence } = verifySources();
const module = renderModule(source, essence);
if (isCheck) {
  if (readFileSync(outputPath, 'utf8') !== module) {
    console.error(
      '✗ src/essence/ucum-essence-xml.ts is out of date. Run `pnpm --filter @callis/ucum embed`.',
    );
    process.exit(1);
  }
  console.log('✓ src/essence/ucum-essence-xml.ts matches data/ucum-essence.xml');
} else {
  writeFileSync(outputPath, module);
  console.log(`Wrote ${outputPath}`);
}
