import { describe, expect, it } from 'vitest';
import type { TypeRow } from '../runtime/provider.ts';
import {
  coreDefinitions,
  emitInventory,
  emitModel,
  emitProvider,
  generateModel,
  type StructureDefinition,
} from './generate.ts';

function definition(type: string, options: Partial<StructureDefinition> = {}): StructureDefinition {
  return {
    resourceType: 'StructureDefinition',
    url: `http://hl7.org/fhir/StructureDefinition/${type}`,
    type,
    kind: 'complex-type',
    abstract: false,
    snapshot: { element: [{ id: type, path: type }] },
    ...options,
  };
}
const element = definition('Element', { abstract: true });
const backbone = definition('BackboneElement', { abstract: true, baseDefinition: element.url });
const string = definition('string', {
  kind: 'primitive-type',
  baseDefinition: element.url,
  snapshot: {
    element: [
      { id: 'string', path: 'string' },
      {
        id: 'string.value',
        path: 'string.value',
        max: '1',
        type: [{ code: 'http://hl7.org/fhirpath/System.String' }],
      },
    ],
  },
});
const tree = definition('Tree', {
  kind: 'resource',
  snapshot: {
    element: [
      { id: 'Tree', path: 'Tree' },
      { id: 'Tree.node', path: 'Tree.node', max: '*', type: [{ code: 'BackboneElement' }] },
      {
        id: 'Tree.node.label[x]',
        path: 'Tree.node.label[x]',
        max: '1',
        type: [{ code: 'string' }],
      },
      { id: 'Tree.node.node', path: 'Tree.node.node', max: '*', contentReference: '#Tree.node' },
      { id: 'Tree.other', path: 'Tree.other', max: '1', contentReference: '#Tree.node' },
    ],
  },
});
const definitions = [element, backbone, string, tree];

// https://hl7.org/fhir/R5/structuredefinition.html#snapshot
// https://hl7.org/fhir/R5/elementdefinition-definitions.html#ElementDefinition.contentReference
// https://hl7.org/fhir/R5/fhirpath.html#polymorphism
describe('snapshot generation', () => {
  it('is byte-identical across repeated generation and input file order', () => {
    const first = emitModel(generateModel(definitions), 'synthetic');
    expect(emitModel(generateModel(definitions), 'synthetic')).toBe(first);
    expect(emitModel(generateModel([...definitions].reverse()), 'synthetic')).toBe(first);
  });
  it('copies the provider builder verbatim under a generated-file header', () => {
    const template = 'export const x = 1;\n';
    expect(emitProvider(template)).toBe(
      `// Generated by tools/model-gen from tools/model-gen/runtime/provider.ts; do not edit.\n${template}`,
    );
  });
  it('inventories all selected roots and backbones deterministically', () => {
    const rows = generateModel(definitions);
    const inventory = emitInventory(rows, 'synthetic@1.0.0');
    expect(emitInventory([...rows].reverse(), 'synthetic@1.0.0')).toBe(inventory);
    expect(JSON.parse(inventory)).toEqual({
      source: 'synthetic@1.0.0',
      total: 5,
      types: {
        resource: ['Tree'],
        complex: ['BackboneElement', 'Element'],
        primitive: ['string'],
        backbone: ['Tree.node'],
      },
    });
    expect(
      rows
        .filter((row) => row[1] !== 'backbone')
        .map((row) => row[0])
        .sort(),
    ).toEqual(
      coreDefinitions(definitions)
        .map((entry) => entry.type)
        .sort(),
    );
  });
  it('resolves recursive and shared content while retaining single-type choices', () => {
    const rows = generateModel(definitions);
    expect(rows.find((row) => row[0] === 'Tree.node')).toEqual([
      'Tree.node',
      'backbone',
      'BackboneElement',
      false,
      null,
      [
        ['label', ['string'], 2],
        ['node', ['Tree.node'], 1],
      ],
    ]);
    expect(rows.find((row) => row[0] === 'Tree')?.[5]).toEqual([
      ['node', ['Tree.node'], 1],
      ['other', ['Tree.node'], 0],
    ]);
    expect(rows.find((row) => row[0] === 'string')?.[5]).toEqual([]);
  });
  it('selects all base resources/datatypes but excludes profiles and logical models', () => {
    expect(
      coreDefinitions([
        ...definitions,
        definition('Profile', { derivation: 'constraint' }),
        definition('Logical', { kind: 'logical' }),
      ]),
    ).toEqual(definitions);
  });
  it('rejects missing snapshots and unresolved inheritance', () => {
    expect(() => generateModel([definition('Broken', { snapshot: { element: [] } })])).toThrow(
      'Missing snapshot',
    );
    expect(() => generateModel([definition('Broken', { baseDefinition: 'missing' })])).toThrow(
      'Unresolved base',
    );
  });
  it('rejects unresolved types and content references', () => {
    const broken = (field: object): StructureDefinition =>
      definition('Broken', {
        snapshot: {
          element: [
            { id: 'Broken', path: 'Broken' },
            { id: 'Broken.child', path: 'Broken.child', max: '1', ...field },
          ],
        },
      });
    expect(() => generateModel([broken({ type: [{ code: 'Missing' }] })])).toThrow(
      'Unresolved type',
    );
    expect(() => generateModel([broken({ contentReference: '#missing' })])).toThrow(
      'Unresolved contentReference',
    );
    expect(() => generateModel([broken({ contentReference: '#Broken.child' })])).toThrow(
      'Cyclic contentReference',
    );
  });
  it('rejects cyclic inheritance and duplicate definitions', () => {
    expect(() =>
      generateModel([
        definition('A', { baseDefinition: 'http://hl7.org/fhir/StructureDefinition/B' }),
        definition('B', { baseDefinition: 'http://hl7.org/fhir/StructureDefinition/A' }),
      ]),
    ).toThrow('Cyclic inheritance');
    expect(() => generateModel([element, element])).toThrow('Duplicate type');
  });
  it('retains snapshot constraints on inherited fields and normalizes System fields', () => {
    const base = definition('Base', {
      snapshot: {
        element: [
          { id: 'Base', path: 'Base' },
          { id: 'Base.field', path: 'Base.field', max: '*', type: [{ code: 'string' }] },
        ],
      },
    });
    const child = definition('Child', {
      baseDefinition: base.url,
      snapshot: {
        element: [
          { id: 'Child', path: 'Child' },
          {
            id: 'Child.field',
            path: 'Child.field',
            max: '1',
            type: [
              {
                code: 'http://hl7.org/fhirpath/System.String',
                extension: [
                  {
                    url: 'http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type',
                    valueUrl: 'string',
                  },
                ],
              },
            ],
          },
        ],
      },
    });
    expect(
      generateModel([element, string, base, child]).find((row) => row[0] === 'Child')?.[5],
    ).toEqual([['field', ['string'], 0]]);
  });
  it('propagates Quantity mappings through more than one specialization', () => {
    const quantity = definition('Quantity');
    const age = definition('Age', { baseDefinition: quantity.url });
    const specializedAge = definition('SpecializedAge', { baseDefinition: age.url });
    expect(generateModel([specializedAge, age, quantity]).map((row) => row[4])).toEqual([
      'Quantity',
      'Quantity',
      'Quantity',
    ]);
  });
});

const SYSTEM_STRING = 'http://hl7.org/fhirpath/System.String';
const FHIR_TYPE = 'http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type';

/** A System-typed `id` element as the pinned sources write it: `base` names its defining element. */
function idElement(path: string, base: string, valueUrl: string) {
  return {
    id: path,
    path,
    base: { path: base },
    max: '1',
    type: [{ code: SYSTEM_STRING, extension: [{ url: FHIR_TYPE, valueUrl }] }],
  };
}
function primitive(type: string, base: StructureDefinition): StructureDefinition {
  return definition(type, {
    kind: 'primitive-type',
    baseDefinition: base.url,
    snapshot: {
      element: [
        { id: type, path: type },
        { id: `${type}.value`, path: `${type}.value`, max: '1', type: [{ code: SYSTEM_STRING }] },
      ],
    },
  });
}
const idPrimitive = primitive('id', string);
const uriPrimitive = primitive('uri', string);
const elementRoot = definition('Element', {
  abstract: true,
  snapshot: {
    element: [{ id: 'Element', path: 'Element' }, idElement('Element.id', 'Element.id', 'string')],
  },
});
/** A root whose own `id` says `valueUrl`, as `Resource.id` does in each source. */
function resourceRoot(valueUrl: string): StructureDefinition {
  return definition('Resource', {
    kind: 'resource',
    abstract: true,
    snapshot: {
      element: [
        { id: 'Resource', path: 'Resource' },
        idElement('Resource.id', 'Resource.id', valueUrl),
      ],
    },
  });
}
/** A definition inheriting `id` from `base`, with the snapshot copy saying `valueUrl`. */
function inheritor(
  type: string,
  kind: string,
  base: StructureDefinition,
  baseElement: string,
  valueUrl: string,
  options: Partial<StructureDefinition> = {},
): StructureDefinition {
  return definition(type, {
    kind,
    baseDefinition: base.url,
    snapshot: {
      element: [{ id: type, path: type }, idElement(`${type}.id`, baseElement, valueUrl)],
    },
    ...options,
  });
}
/** The shared fixture; `copies` is what the snapshot copies of the inherited `id` say. */
function idDefinitions(
  resourceId: string,
  copies: { readonly resource: string; readonly datatype: string },
  patient: Partial<StructureDefinition> = {},
): StructureDefinition[] {
  const resource = resourceRoot(resourceId);
  return [
    elementRoot,
    resource,
    string,
    idPrimitive,
    uriPrimitive,
    inheritor('Patient', 'resource', resource, 'Resource.id', copies.resource, patient),
    inheritor('Address', 'complex-type', elementRoot, 'Element.id', copies.datatype),
  ];
}
function idTypes(rows: readonly TypeRow[]): Record<string, readonly string[] | undefined> {
  return Object.fromEntries(
    rows
      .filter((row) => row[1] !== 'primitive')
      .map((row) => [row[0], row[5].find(([field]) => field === 'id')?.[1]]),
  );
}

// https://hl7.org/fhir/R5/elementdefinition-definitions.html#ElementDefinition.base
// https://hl7.org/fhir/R5/structuredefinition.html#snapshot
describe('System-typed elements and structuredefinition-fhir-type', () => {
  it('gives an inherited element the type of the element that defines it', () => {
    // The shapes of R6 (Patient.id says string, Resource.id says id) and of R5 (Address.id says
    // id, Element.id says string): the snapshot copy of an inherited element has no say.
    const rows = generateModel(idDefinitions('id', { resource: 'string', datatype: 'id' }));
    expect(idTypes(rows)).toEqual({
      Element: ['string'],
      Resource: ['id'],
      Patient: ['id'],
      Address: ['string'],
    });
  });
  it('is not affected by the order of the definitions', () => {
    const definitions = idDefinitions('id', { resource: 'string', datatype: 'id' });
    expect(generateModel([...definitions].reverse())).toEqual(generateModel(definitions));
  });
  it('keeps the snapshot type of an element that the differential redefines', () => {
    const rows = generateModel(
      idDefinitions(
        'id',
        { resource: 'uri', datatype: 'string' },
        { differential: { element: [{ id: 'Patient.id' }] } },
      ),
    );
    expect(idTypes(rows)).toMatchObject({ Resource: ['id'], Patient: ['uri'] });
  });
  it('rejects an inherited element whose defining element is missing or differs in type', () => {
    const resource = resourceRoot('id');
    const generate = (base: StructureDefinition, baseElement: string) =>
      generateModel([
        elementRoot,
        base,
        string,
        idPrimitive,
        inheritor('Patient', 'resource', base, baseElement, 'id'),
      ]);
    expect(() => generate(resource, 'Missing.id')).toThrow('Unresolved base element: Missing.id');
    expect(() => generate(resource, 'Resource.meta')).toThrow(
      'Unresolved base element: Resource.meta',
    );
    const integer = definition('Resource', {
      kind: 'resource',
      snapshot: {
        element: [
          { id: 'Resource', path: 'Resource' },
          {
            id: 'Resource.id',
            path: 'Resource.id',
            max: '1',
            type: [{ code: 'http://hl7.org/fhirpath/System.Integer' }],
          },
        ],
      },
    });
    expect(() => generate(integer, 'Resource.id')).toThrow(
      'Base element differs in type: Patient.id: Resource.id',
    );
  });

  describe('corrections of a source', () => {
    const resourceId = { path: 'Resource.id', from: 'string', to: 'id' } as const;
    // The shape of R4 4.0.1, where Resource.id and every copy of it say string.
    const r4 = (): StructureDefinition[] =>
      idDefinitions('string', { resource: 'string', datatype: 'string' });
    it('apply where the element is defined, and inheriting elements follow', () => {
      expect(idTypes(generateModel(r4(), { corrections: [resourceId] }))).toEqual({
        Element: ['string'],
        Resource: ['id'],
        Patient: ['id'],
        Address: ['string'],
      });
    });
    it('are not applied unless they are given', () => {
      expect(idTypes(generateModel(r4()))).toMatchObject({ Resource: ['string'] });
    });
    it('fail when the source no longer carries the value they correct', () => {
      expect(() =>
        generateModel(idDefinitions('id', { resource: 'id', datatype: 'string' }), {
          corrections: [resourceId],
        }),
      ).toThrow('Stale correction: Resource.id is id, the correction expects string');
    });
    it('fail when no element uses them', () => {
      expect(() =>
        generateModel(r4(), {
          corrections: [resourceId, { path: 'Resource.status', from: 'string', to: 'code' }],
        }),
      ).toThrow('Unused correction: Resource.status');
    });
  });
});
