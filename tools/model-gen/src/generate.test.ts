import { describe, expect, it } from 'vitest';
import {
  coreDefinitions,
  emitModel,
  emitProvider,
  generateModel,
  type StructureDefinition,
} from './generate.ts';

function definition(type: string, options: Partial<StructureDefinition> = {}): StructureDefinition {
  return {
    resourceType: 'StructureDefinition',
    url: `http://hl7.org/fhir/StructureDefinition/${type}`,
    type,
    kind: 'complex-type',
    abstract: false,
    snapshot: { element: [{ id: type, path: type }] },
    ...options,
  };
}
const element = definition('Element', { abstract: true });
const backbone = definition('BackboneElement', { abstract: true, baseDefinition: element.url });
const string = definition('string', {
  kind: 'primitive-type',
  baseDefinition: element.url,
  snapshot: {
    element: [
      { id: 'string', path: 'string' },
      {
        id: 'string.value',
        path: 'string.value',
        max: '1',
        type: [{ code: 'http://hl7.org/fhirpath/System.String' }],
      },
    ],
  },
});
const tree = definition('Tree', {
  kind: 'resource',
  snapshot: {
    element: [
      { id: 'Tree', path: 'Tree' },
      { id: 'Tree.node', path: 'Tree.node', max: '*', type: [{ code: 'BackboneElement' }] },
      {
        id: 'Tree.node.label[x]',
        path: 'Tree.node.label[x]',
        max: '1',
        type: [{ code: 'string' }],
      },
      { id: 'Tree.node.node', path: 'Tree.node.node', max: '*', contentReference: '#Tree.node' },
      { id: 'Tree.other', path: 'Tree.other', max: '1', contentReference: '#Tree.node' },
    ],
  },
});
const definitions = [element, backbone, string, tree];

// https://hl7.org/fhir/R5/structuredefinition.html#snapshot
// https://hl7.org/fhir/R5/elementdefinition-definitions.html#ElementDefinition.contentReference
// https://hl7.org/fhir/R5/fhirpath.html#polymorphism
describe('snapshot generation', () => {
  it('is byte-identical across repeated generation and input file order', () => {
    const first = emitModel(generateModel(definitions), 'synthetic');
    expect(emitModel(generateModel(definitions), 'synthetic')).toBe(first);
    expect(emitModel(generateModel([...definitions].reverse()), 'synthetic')).toBe(first);
  });
  it('copies the provider builder verbatim under a generated-file header', () => {
    const template = 'export const x = 1;\n';
    expect(emitProvider(template)).toBe(
      `// Generated by tools/model-gen from tools/model-gen/runtime/provider.ts; do not edit.\n${template}`,
    );
  });
  it('resolves recursive and shared content while retaining single-type choices', () => {
    const rows = generateModel(definitions);
    expect(rows.find((row) => row[0] === 'Tree.node')).toEqual([
      'Tree.node',
      'backbone',
      'BackboneElement',
      false,
      null,
      [
        ['label', ['string'], 2],
        ['node', ['Tree.node'], 1],
      ],
    ]);
    expect(rows.find((row) => row[0] === 'Tree')?.[5]).toEqual([
      ['node', ['Tree.node'], 1],
      ['other', ['Tree.node'], 0],
    ]);
    expect(rows.find((row) => row[0] === 'string')?.[5]).toEqual([]);
  });
  it('selects all base resources/datatypes but excludes profiles and logical models', () => {
    expect(
      coreDefinitions([
        ...definitions,
        definition('Profile', { derivation: 'constraint' }),
        definition('Logical', { kind: 'logical' }),
      ]),
    ).toEqual(definitions);
  });
  it('rejects missing snapshots and unresolved inheritance', () => {
    expect(() => generateModel([definition('Broken', { snapshot: { element: [] } })])).toThrow(
      'Missing snapshot',
    );
    expect(() => generateModel([definition('Broken', { baseDefinition: 'missing' })])).toThrow(
      'Unresolved base',
    );
  });
  it('rejects unresolved types and content references', () => {
    const broken = (field: object): StructureDefinition =>
      definition('Broken', {
        snapshot: {
          element: [
            { id: 'Broken', path: 'Broken' },
            { id: 'Broken.child', path: 'Broken.child', max: '1', ...field },
          ],
        },
      });
    expect(() => generateModel([broken({ type: [{ code: 'Missing' }] })])).toThrow(
      'Unresolved type',
    );
    expect(() => generateModel([broken({ contentReference: '#missing' })])).toThrow(
      'Unresolved contentReference',
    );
    expect(() => generateModel([broken({ contentReference: '#Broken.child' })])).toThrow(
      'Cyclic contentReference',
    );
  });
  it('rejects cyclic inheritance and duplicate definitions', () => {
    expect(() =>
      generateModel([
        definition('A', { baseDefinition: 'http://hl7.org/fhir/StructureDefinition/B' }),
        definition('B', { baseDefinition: 'http://hl7.org/fhir/StructureDefinition/A' }),
      ]),
    ).toThrow('Cyclic inheritance');
    expect(() => generateModel([element, element])).toThrow('Duplicate type');
  });
  it('retains snapshot constraints on inherited fields and normalizes System fields', () => {
    const base = definition('Base', {
      snapshot: {
        element: [
          { id: 'Base', path: 'Base' },
          { id: 'Base.field', path: 'Base.field', max: '*', type: [{ code: 'string' }] },
        ],
      },
    });
    const child = definition('Child', {
      baseDefinition: base.url,
      snapshot: {
        element: [
          { id: 'Child', path: 'Child' },
          {
            id: 'Child.field',
            path: 'Child.field',
            max: '1',
            type: [
              {
                code: 'http://hl7.org/fhirpath/System.String',
                extension: [
                  {
                    url: 'http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type',
                    valueUrl: 'string',
                  },
                ],
              },
            ],
          },
        ],
      },
    });
    expect(
      generateModel([element, string, base, child]).find((row) => row[0] === 'Child')?.[5],
    ).toEqual([['field', ['string'], 0]]);
  });
  it('propagates Quantity mappings through more than one specialization', () => {
    const quantity = definition('Quantity');
    const age = definition('Age', { baseDefinition: quantity.url });
    const specializedAge = definition('SpecializedAge', { baseDefinition: age.url });
    expect(generateModel([specializedAge, age, quantity]).map((row) => row[4])).toEqual([
      'Quantity',
      'Quantity',
      'Quantity',
    ]);
  });
});
