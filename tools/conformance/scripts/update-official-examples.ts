/**
 * Vendors the official FHIR JSON examples that the converted fixtures are compared with (T0023):
 * the files named in `OFFICIAL_EXAMPLES`, from the checksum-pinned `hl7.fhir.r4.examples` and
 * `hl7.fhir.r5.examples` packages. Writes them to `official-examples/<suite>/`, with
 * `official-examples/source.json` (checksums) and `official-examples/SOURCE.md`, and removes
 * examples that are no longer named.
 *
 * Usage: `pnpm --filter @callis/conformance update-official-examples`. Needs network access, `tar`,
 * and about 40 MB of downloads.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  EXAMPLE_PACKAGES,
  OFFICIAL_EXAMPLES,
  OFFICIAL_EXAMPLES_DIR,
} from '../src/official-examples.ts';
import { compareOrdinal } from '../src/ordinal.ts';
import { SUITE_IDS } from '../src/suite.ts';

const files: Record<string, { readonly package: string; readonly sha256: string }> = {};

for (const suite of SUITE_IDS) {
  const examplePackage = EXAMPLE_PACKAGES[suite];
  const source = `${examplePackage.name}@${examplePackage.version}`;
  const url = `https://packages.fhir.org/${examplePackage.name}/${examplePackage.version}`;
  const response = await fetch(url, { signal: AbortSignal.timeout(300_000) });
  if (!response.ok) {
    throw new Error(`GET ${url}: ${response.status} ${response.statusText}`);
  }
  const archive = new Uint8Array(await response.arrayBuffer());
  if (sha256(archive) !== examplePackage.sha256) {
    throw new Error(`${source}: the archive does not match its pinned SHA-256`);
  }
  const names = OFFICIAL_EXAMPLES.filter((example) => example.suite === suite)
    .map((example) => example.official)
    .sort(compareOrdinal);
  const staging = mkdtempSync(join(tmpdir(), 'callis-official-examples-'));
  try {
    const archivePath = join(staging, 'package.tgz');
    writeFileSync(archivePath, archive);
    // Extract only the named files, and only from the checksum-pinned archive.
    execFileSync('tar', [
      '-xzf',
      archivePath,
      '-C',
      staging,
      'package/package.json',
      ...names.map((name) => `package/${name}`),
    ]);
    const manifest: unknown = JSON.parse(
      readFileSync(join(staging, 'package/package.json'), 'utf8'),
    );
    if (
      property(manifest, 'name') !== examplePackage.name ||
      property(manifest, 'version') !== examplePackage.version ||
      property(manifest, 'license') !== 'CC0-1.0'
    ) {
      throw new Error(`${source}: unexpected package name, version or license`);
    }
    const target = join(OFFICIAL_EXAMPLES_DIR, suite);
    mkdirSync(target, { recursive: true });
    for (const stale of readdirSync(target).filter((name) => !names.includes(name))) {
      rmSync(join(target, stale));
      console.log(`  removed ${suite}/${stale}`);
    }
    for (const name of names) {
      const content = readFileSync(join(staging, 'package', name));
      writeFileSync(join(target, name), content);
      files[`${suite}/${name}`] = { package: source, sha256: sha256(content) };
      console.log(`  ${suite}/${name}`);
    }
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

writeFileSync(
  join(OFFICIAL_EXAMPLES_DIR, 'source.json'),
  `${JSON.stringify({ files }, null, 2)}\n`,
);
writeFileSync(join(OFFICIAL_EXAMPLES_DIR, 'SOURCE.md'), renderSourceMarkdown());
console.log(`Vendored ${Object.keys(files).length} official examples.`);

function sha256(content: Uint8Array): string {
  return createHash('sha256').update(content).digest('hex');
}

function property(value: unknown, name: string): unknown {
  return typeof value === 'object' && value !== null && Object.hasOwn(value, name)
    ? Reflect.get(value, name)
    : undefined;
}

function renderSourceMarkdown(): string {
  const packages = SUITE_IDS.map((suite) => {
    const { name, version, sha256: checksum } = EXAMPLE_PACKAGES[suite];
    return `| \`${suite}/\` | [\`${name}@${version}\`](https://packages.fhir.org/${name}/${version}) | \`${checksum}\` |`;
  });
  return `# Official FHIR JSON examples

<!-- Generated by \`pnpm --filter @callis/conformance update-official-examples\`. Do not edit by hand. -->

Unchanged copies of the official JSON examples that the converted suite inputs are compared with ([T0023](../../../docs/tasks/T0023-xml-fixture-conversion.md), \`src/official-examples.ts\`). Only the files named in \`OFFICIAL_EXAMPLES\` are copied, from these packages:

| Folder | Package | SHA-256 of the archive |
| --- | --- | --- |
${packages.join('\n')}

[\`source.json\`](source.json) records the SHA-256 of every file; a unit test checks that the files are unchanged.

## License

The FHIR examples packages are licensed under [CC0-1.0](https://creativecommons.org/publicdomain/zero/1.0/) (the \`license\` in each package's \`package.json\`).
`;
}
