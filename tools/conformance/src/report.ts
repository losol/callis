/**
 * Renders the conformance reports: the Markdown reports (generated into `docs/conformance/`, never
 * committed), the JSON summary (a CI artifact) and the CI job summary. Output is deterministic (no
 * dates), so a report only changes when an outcome changes.
 */
import type { RatchetMode, RatchetResult } from './baseline.ts';
import { formatRefs } from './baseline.ts';
import { PHASE_LABELS, PHASES } from './classify.ts';
import type { FixtureSource } from './fixtures.ts';
import type { SuiteRun, TestResult } from './run-suite.ts';
import type { SuiteId } from './suite.ts';
import type { Counts, SuiteSummary } from './summary.ts';

/** What every report says about the run. */
export interface ReportContext {
  /** The adapter's name. */
  readonly adapter: string;
  readonly source: FixtureSource;
}

/** Suite display names. */
const SUITE_LABELS: Readonly<Record<SuiteId, string>> = { r4: 'R4', r5: 'R5' };

/** From `docs/conformance/` to `tools/conformance/`. */
const TOOL_PATH = '../../tools/conformance';

const MAX_EXPRESSION = 100;
const MAX_PROBLEM = 200;

/** The Markdown report of one suite, for `docs/conformance/<suite>.md`. */
export function renderSuiteReport(
  run: SuiteRun,
  summary: SuiteSummary,
  context: ReportContext,
): string {
  const { source } = context;
  const suiteLink = `${TOOL_PATH}/fixtures/${run.suite.id}/${run.suite.fileName}`;
  const lines: string[] = [
    `# FHIRPath conformance: ${SUITE_LABELS[run.suite.id]} suite`,
    '',
    '<!-- Generated by `pnpm conformance`. Do not edit by hand. -->',
    '',
    `Results of [\`${run.suite.fileName}\`](${suiteLink}) from ${sourceLink(source)}, evaluated with the **${context.adapter}** adapter. How tests are classified, run and compared is described in [tools/conformance](${TOOL_PATH}/README.md).`,
    '',
    '## Summary',
    '',
    '| Phase | Tests | Passed | Failed | Skipped |',
    '| --- | ---: | ---: | ---: | ---: |',
    ...PHASES.map((phase) => countsRow(PHASE_LABELS[phase], summary.phases[phase])),
    countsRow('**Total**', summary.counts),
  ];
  if (summary.detectedLate > 0) {
    lines.push(
      '',
      `${summary.detectedLate} of the passed tests expect a semantic error that was only detected during evaluation ("detected late"; [N1 §11](https://hl7.org/fhirpath/N1/#type-safety-and-strict-evaluation)).`,
    );
  }
  if (summary.skipReasons.length > 0) {
    lines.push('', '## Skipped tests', '', '| Reason | Tests |', '| --- | ---: |');
    for (const { reason, count } of summary.skipReasons) {
      lines.push(`| ${linkSpecNotes(cell(reason))} | ${count} |`);
    }
  }

  const failures = run.results.filter((result) => result.status === 'fail');
  const failingGroups = new Set(failures.map((result) => result.test.group));
  lines.push(
    '',
    '## Groups',
    '',
    '| Group | Phase | Tests | Passed | Failed | Skipped |',
    '| --- | --- | ---: | ---: | ---: | ---: |',
  );
  for (const group of summary.groups) {
    const name = failingGroups.has(group.name)
      ? `[${code(group.name)}](#${slug(group.name)})`
      : code(group.name);
    const phases = group.phases.map((phase) => PHASE_LABELS[phase]).join(', ');
    const { total, passed, failed, skipped } = group.counts;
    lines.push(`| ${name} | ${phases} | ${total} | ${passed} | ${failed} | ${skipped} |`);
  }

  lines.push('', '## Failing tests', '');
  if (failures.length === 0) {
    lines.push('None.');
  }
  for (const group of summary.groups) {
    const groupFailures = failures.filter((result) => result.test.group === group.name);
    if (groupFailures.length === 0) {
      continue;
    }
    lines.push(
      `### ${group.name}`,
      '',
      '| Test | Phase | Expression | Problem |',
      '| --- | --- | --- | --- |',
    );
    for (const result of groupFailures) {
      lines.push(failureRow(result, suiteLink));
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** The JSON summary of all suites, for the CI artifact (`--summary <file>`). */
export function renderJsonSummary(
  summaries: readonly SuiteSummary[],
  context: ReportContext,
): string {
  const data = {
    description: 'Conformance summary. Generated by `pnpm conformance`; do not edit by hand.',
    adapter: context.adapter,
    fixtures: { repository: context.source.repository, commit: context.source.commit },
    suites: Object.fromEntries(
      summaries.map((summary) => [
        summary.suite,
        {
          file: summary.file,
          ...summary.counts,
          detectedLate: summary.detectedLate,
          phases: summary.phases,
          groups: Object.fromEntries(
            summary.groups.map((group) => [group.name, { phases: group.phases, ...group.counts }]),
          ),
        },
      ]),
    ),
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}

/** The Markdown for the CI job summary: counts per suite and phase, and the ratchet result. */
export function renderJobSummary(
  summaries: readonly SuiteSummary[],
  ratchet: RatchetResult,
  context: ReportContext,
): string {
  const lines = [
    '## FHIRPath conformance',
    '',
    `Adapter: ${context.adapter}. Fixtures: ${sourceLink(context.source)}.`,
    '',
    '| Suite | Phase | Tests | Passed | Failed | Skipped |',
    '| --- | --- | ---: | ---: | ---: | ---: |',
  ];
  for (const summary of summaries) {
    const label = SUITE_LABELS[summary.suite];
    for (const phase of PHASES) {
      lines.push(`| ${label} ${countsRow(PHASE_LABELS[phase], summary.phases[phase])}`);
    }
  }
  lines.push('', ...ratchetMessages(ratchet, 'check').map((message) => `- ${message}`), '');
  return lines.join('\n');
}

/**
 * Human-readable lines about the ratchet. Baseline changes the run has not recorded yet fail only
 * in `check` mode, so they are marked ❌ there and ℹ️ otherwise.
 */
export function ratchetMessages(ratchet: RatchetResult, mode: RatchetMode): string[] {
  const messages: string[] = [];
  if (ratchet.regressions.length > 0) {
    messages.push(
      `❌ ${ratchet.regressions.length} test(s) in the baseline no longer pass: ${formatRefs(ratchet.regressions)}.`,
    );
  } else {
    messages.push('✅ No regressions: every test in the baseline still passes.');
  }
  const mark = mode === 'check' ? '❌' : 'ℹ️';
  const update =
    'Run `pnpm conformance --update-baseline` and commit `tools/conformance/baseline/`.';
  if (ratchet.vanished.length > 0) {
    messages.push(
      `${mark} ${ratchet.vanished.length} baseline test(s) are no longer in the suite: ${formatRefs(ratchet.vanished)}. ${update}`,
    );
  }
  if (ratchet.excluded.length > 0) {
    messages.push(
      `${mark} ${ratchet.excluded.length} baseline test(s) are now skipped as exceptions or unsupported: ${formatRefs(ratchet.excluded)}. ${update}`,
    );
  }
  if (ratchet.newPasses.length > 0) {
    messages.push(
      `${mark} ${ratchet.newPasses.length} test(s) pass but are not in the baseline yet: ${formatRefs(ratchet.newPasses)}. ${update}`,
    );
  }
  return messages;
}

function failureRow(result: TestResult, suiteLink: string): string {
  const { test, classification } = result;
  const name = `[${code(test.id)}](${suiteLink}#L${test.line})`;
  const phase =
    classification.task === undefined
      ? PHASE_LABELS[classification.phase]
      : `${PHASE_LABELS[classification.phase]} (${classification.task})`;
  const problem = result.failure === undefined ? '' : truncate(result.failure.summary, MAX_PROBLEM);
  return `| ${name} | ${phase} | ${code(truncate(test.expression, MAX_EXPRESSION))} | ${cell(problem)} |`;
}

function countsRow(label: string, counts: Counts): string {
  return `| ${label} | ${counts.total} | ${counts.passed} | ${counts.failed} | ${counts.skipped} |`;
}

function sourceLink(source: FixtureSource): string {
  const url = `https://github.com/${source.repository}/tree/${source.commit}`;
  return `[${source.repository}@${source.commit.slice(0, 7)}](${url})`;
}

/** Turns the `spec-notes#anchor` of an exception's skip reason into a link to that note. */
function linkSpecNotes(text: string): string {
  return text.replace(/spec-notes#([\w-]+)/g, '[spec notes](../spec-notes.md#$1)');
}

/** A table cell: one line, pipes escaped. */
function cell(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

/** A code span in a table cell, safe for backticks and pipes inside. */
function code(text: string): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  const longestRun = Math.max(0, ...(flat.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(longestRun + 1);
  const padding = flat.startsWith('`') || flat.endsWith('`') ? ' ' : '';
  return `${fence}${padding}${flat.replace(/\|/g, '\\|')}${padding}${fence}`;
}

function truncate(text: string, max: number): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

/** The anchor GitHub gives a heading. */
export function slug(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}
